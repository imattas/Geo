pub fn native_runtime() -> NativeRuntime {
    NativeRuntime {
        name: "geo_native_runtime",
        source_path: workspace_root()
            .join("library")
            .join("geo_runtime")
            .join("geo_runtime.c"),
    }
}

pub fn c_runtime_path() -> PathBuf {
    native_runtime().source_path
}

fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("..").join("..")
}

fn runtime_fn(
    path: &[String],
    name: &str,
    params: Vec<Param>,
    return_type: Type,
) -> RuntimeFunction {
    runtime_fn_with_symbol(path, name, name, params, return_type)
}

fn runtime_fn_with_symbol(
    path: &[String],
    name: &str,
    symbol: &str,
    params: Vec<Param>,
    return_type: Type,
) -> RuntimeFunction {
    RuntimeFunction {
        module: path.to_vec(),
        name: name.to_string(),
        symbol: symbol.to_string(),
        params,
        return_type,
    }
}

fn param(name: &str, ty: Type) -> Param {
    Param {
        name: name.to_string(),
        ty,
    }
}
