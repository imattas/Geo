#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct Span {
    pub line: usize,
    pub column: usize,
    pub offset: usize,
    pub len: usize,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Token {
    pub kind: TokenKind,
    pub span: Span,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum TokenKind {
    Fn,
    Import,
    Extern,
    Return,
    Let,
    Var,
    Const,
    Type,
    Mut,
    Struct,
    Enum,
    If,
    Else,
    While,
    For,
    In,
    Loop,
    Match,
    Unsafe,
    Break,
    Continue,
    As,
    Sizeof,
    Alignof,
    Offsetof,
    Null,
    True,
    False,
    Int,
    Bool,
    Char,
    String,
    Str,
    Usize,
    I8,
    I16,
    I32,
    I64,
    U8,
    U16,
    U32,
    U64,
    Ident(String),
    IntLiteral(i64),
    TypedIntLiteral(i64, String),
    StringLiteral(String),
    CharLiteral(char),
    LeftParen,
    RightParen,
    LeftBrace,
    RightBrace,
    LeftBracket,
    RightBracket,
    Colon,
    Comma,
    Dot,
    DotDot,
    DotDotEqual,
    Semicolon,
    Ampersand,
    AmpersandAmpersand,
    Pipe,
    PipePipe,
    Caret,
    Plus,
    Minus,
    Star,
    Slash,
    Percent,
    PlusEqual,
    MinusEqual,
    StarEqual,
    SlashEqual,
    PercentEqual,
    AmpersandEqual,
    PipeEqual,
    CaretEqual,
    ShiftLeftEqual,
    ShiftRightEqual,
    Equal,
    EqualEqual,
    Bang,
    BangEqual,
    Tilde,
    Less,
    ShiftLeft,
    LessEqual,
    Greater,
    ShiftRight,
    GreaterEqual,
    Arrow,
    FatArrow,
    Eof,
}
